"use client";

import React, { useEffect, useId, useRef, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { AlertTriangle, FileSignature, Info, ShieldAlert, Upload } from "lucide-react";
import { useLanguage } from "@/components/LanguageProvider";
import { inspectBlob } from "@/lib/c2pa-inspect";
import type { AiUseChoice } from "@/lib/c2pa-server";

interface ProfileOption {
  id: string;
  displayName: string;
  website: string | null;
  defaultTrainingPreference: boolean;
}

const DISCLOSURE_OPTIONS: Array<{
  value: AiUseChoice;
  label: string;
  specHint: string;
  requiresModelType: boolean;
}> = [
  {
    value: "full_ai",
    label: "Fully generated by AI",
    specHint: "c2pa.created + trainedAlgorithmicMedia",
    requiresModelType: true,
  },
  {
    value: "original_edited_ai",
    label: "My original, edited or enhanced with AI",
    specHint: "c2pa.opened + parent ingredient + c2pa.edited + compositeWithTrainedAlgorithmicMedia",
    requiresModelType: true,
  },
  {
    value: "composite_ai",
    label: "Composite with at least one AI element",
    specHint: "c2pa.edited + compositeSynthetic",
    requiresModelType: true,
  },
  {
    value: "human_edits_ai",
    label: "Human edits to an AI-generated asset",
    specHint: "c2pa.opened + AI parent ingredient kept + humanEdits",
    requiresModelType: false,
  },
  {
    value: "no_ai",
    label: "Made by people, no generative AI",
    specHint: "humanEdits (Self-declared; blocked if an AI ingredient exists)",
    requiresModelType: false,
  },
];

export function SignerClient({
  isAuthenticated,
  isTestMode,
  profiles = [],
  creditBalance = 0,
}: {
  isAuthenticated: boolean;
  isTestMode: boolean;
  profiles?: ProfileOption[];
  creditBalance?: number;
}) {
  const router = useRouter();
  const { t } = useLanguage();
  const fileInputId = useId();
  const creatorId = useId();
  const websiteId = useId();
  const modelTypeId = useId();
  const modelNameId = useId();
  const fileInputRef = useRef<HTMLInputElement>(null);

  const [files, setFiles] = useState<File[]>([]);
  const [creatorName, setCreatorName] = useState(profiles[0]?.displayName || "");
  const [creatorWebsite, setCreatorWebsite] = useState(profiles[0]?.website || "");
  const [doNotTrain, setDoNotTrain] = useState(
    profiles[0]?.defaultTrainingPreference ?? true
  );
  const [aiUse, setAiUse] = useState<AiUseChoice>("full_ai");
  const [modelType, setModelType] = useState("imageGeneration");
  const [modelName, setModelName] = useState("");
  const [hasAiIngredient, setHasAiIngredient] = useState(false);
  const [invalidExistingFile, setInvalidExistingFile] = useState<string | null>(null);
  const [checkingFiles, setCheckingFiles] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [sessionExpired, setSessionExpired] = useState(false);
  const [idempotencyKey] = useState(() => crypto.randomUUID());

  useEffect(() => {
    if (hasAiIngredient && aiUse === "no_ai") {
      setAiUse("human_edits_ai");
    }
  }, [hasAiIngredient, aiUse]);

  const handleFilesSelected = async (incoming: FileList | null) => {
    if (!incoming) return;
    const list = Array.from(incoming).slice(0, 50);
    setFiles(list);
    setErrorMsg(null);
    setHasAiIngredient(false);
    setInvalidExistingFile(null);
    setCheckingFiles(true);

    try {
      for (const f of list) {
        if (!["image/jpeg", "image/png"].includes(f.type)) {
          setErrorMsg(`Only JPG or PNG files are supported for signing ("${f.name}").`);
          break;
        }
        const res = await inspectBlob(f, f.name);
        try {
          if (res.status === "warning") {
            setInvalidExistingFile(
              `File "${f.name}" has invalid existing Content Credentials and cannot be signed (Guardrail G3).`
            );
          }
          if (res.rootNode?.aiInfo.isAiGeneratedOrModified) {
            setHasAiIngredient(true);
          }
        } finally {
          res.cleanup();
        }
      }
    } catch {
      // Server still validates all files strictly
    } finally {
      setCheckingFiles(false);
    }
  };

  const selectedOption = DISCLOSURE_OPTIONS.find((o) => o.value === aiUse)!;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!isAuthenticated) {
      router.push("/login?callbackUrl=/app/sign");
      return;
    }
    if (files.length === 0) {
      setErrorMsg("Select at least one JPG or PNG file.");
      return;
    }
    if (invalidExistingFile) {
      setErrorMsg(invalidExistingFile);
      return;
    }

    setSubmitting(true);
    setErrorMsg(null);
    setSessionExpired(false);

    try {
      const fd = new FormData();
      for (const f of files) fd.append("files", f);
      fd.append("creatorName", creatorName);
      fd.append("creatorWebsite", creatorWebsite);
      fd.append("aiUse", aiUse);
      fd.append("modelType", modelType);
      fd.append("modelName", modelName);
      fd.append("doNotTrain", String(doNotTrain));
      fd.append("idempotencyKey", idempotencyKey);

      const res = await fetch("/api/jobs", {
        method: "POST",
        credentials: "same-origin",
        headers: { "Idempotency-Key": idempotencyKey },
        body: fd,
      });

      const data = await res.json();
      if (res.status === 401) {
        setSessionExpired(true);
        setErrorMsg(
          "Your session has expired. Please sign in again to submit your signing job."
        );
        return;
      }
      if (!res.ok) {
        setErrorMsg(data.error || "Failed to submit signing job.");
        return;
      }
      router.push(`/app/jobs/${data.jobId}`);
    } catch {
      setErrorMsg("Network error submitting signing job.");
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="space-y-6">
      {isTestMode && (
        <div
          role="status"
          className="rounded-[12px] border border-[var(--color-brand-line)] bg-[var(--color-brand-soft)] px-4 py-3 text-xs font-semibold text-[var(--color-auth-ink)] flex items-center gap-2.5"
        >
          <Info aria-hidden="true" className="h-4 w-4 shrink-0 text-[var(--color-brand)]" />
          <span>{t.signer.testBanner}</span>
        </div>
      )}

      <section className="space-y-1">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <h1 className="text-2xl sm:text-3xl font-bold text-[var(--color-ink)]">
            {t.signer.title}
          </h1>
          {isAuthenticated && (
            <span className="rounded-full bg-[var(--color-brand-soft)] border border-[var(--color-brand-line)] px-3.5 py-1 text-xs font-semibold text-[var(--color-brand)]">
              Balance: {creditBalance} credits
            </span>
          )}
        </div>
        <p className="text-sm text-[var(--color-text-muted)]">{t.signer.subtitle}</p>
      </section>

      {!isAuthenticated && (
        <div className="glass-surface p-4 text-xs text-[var(--plum)] flex flex-wrap items-center justify-between gap-3">
          <span>Sign in to submit batch signing jobs and download signed files.</span>
          <Link
            href="/login?callbackUrl=/app/sign"
            className="btn-plum px-4 py-2 font-semibold"
          >
            Sign in to continue
          </Link>
        </div>
      )}

      <form onSubmit={handleSubmit} className="space-y-6">
        {/* Step 1: Files */}
        <div className="glass-surface p-6 space-y-4">
          <h2 className="text-base font-semibold text-[var(--espresso-black)]">
            1. Select up to 50 JPG or PNG files
          </h2>

          <div className="rounded-[16px] border-2 border-dashed border-[var(--solar-orange)]/35 bg-[var(--warm-peach)]/40 p-6 text-center space-y-3">
            <Upload aria-hidden="true" className="mx-auto h-8 w-8 text-[var(--color-brand)]" />
            <label htmlFor={fileInputId} className="visually-hidden">
              Select JPG or PNG files
            </label>
            <input
              ref={fileInputRef}
              id={fileInputId}
              type="file"
              multiple
              accept="image/jpeg,image/png,.jpg,.jpeg,.png"
              className="visually-hidden"
              onChange={(e) => handleFilesSelected(e.target.files)}
            />
            <button
              type="button"
              onClick={() => fileInputRef.current?.click()}
              className="btn-mint px-4 py-2 text-sm font-semibold"
            >
              {checkingFiles ? "Checking files…" : "Choose JPG / PNG files"}
            </button>
            {files.length > 0 && (
              <p className="text-xs text-[var(--color-muted)]">
                {files.length} file(s) selected ({files.length} credit{files.length === 1 ? "" : "s"})
              </p>
            )}
          </div>

          {invalidExistingFile && (
            <div
              role="alert"
              className="rounded-[16px] border border-[#C83C4D]/30 bg-rose-50 p-3 text-xs text-rose-950 flex items-center gap-2"
            >
              <ShieldAlert aria-hidden="true" className="h-4 w-4 shrink-0 text-[#C83C4D]" />
              <span>{invalidExistingFile}</span>
            </div>
          )}
        </div>

        {/* Step 2: Attribution */}
        <div className="glass-surface p-6 space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <h2 className="text-base font-semibold text-[var(--espresso-black)]">
              2. Attribution details
            </h2>
            <span className="rounded-full bg-[var(--warm-divider)] px-2.5 py-0.5 text-[11px] font-medium text-[var(--warm-stone)]">
              {t.signer.selfDeclaredNote}
            </span>
          </div>

          {profiles.length > 0 && (
            <div className="flex flex-wrap gap-2">
              {profiles.map((p) => (
                <button
                  key={p.id}
                  type="button"
                  onClick={() => {
                    setCreatorName(p.displayName);
                    setCreatorWebsite(p.website || "");
                    setDoNotTrain(p.defaultTrainingPreference);
                  }}
                  className="rounded-full border border-[var(--border)] bg-white/85 px-3.5 py-1.5 text-xs font-medium text-[var(--espresso-black)] hover:bg-[var(--warm-peach)] hover:border-[var(--color-brand-line)] transition-colors duration-150"
                >
                  Use profile: {p.displayName}
                </button>
              ))}
            </div>
          )}

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div className="space-y-1">
              <label htmlFor={creatorId} className="block text-xs font-medium text-[var(--espresso-black)]">
                {t.signer.creatorName} *
              </label>
              <input
                id={creatorId}
                type="text"
                required
                value={creatorName}
                onChange={(e) => setCreatorName(e.target.value)}
                className="w-full glass-input px-3.5 py-2 text-sm"
              />
            </div>

            <div className="space-y-1">
              <label htmlFor={websiteId} className="block text-xs font-medium text-[var(--espresso-black)]">
                {t.signer.website}
              </label>
              <input
                id={websiteId}
                type="url"
                placeholder="https://example.com"
                value={creatorWebsite}
                onChange={(e) => setCreatorWebsite(e.target.value)}
                className="w-full glass-input px-3.5 py-2 text-sm"
              />
            </div>
          </div>

          <label className="flex items-center gap-2 text-xs text-[var(--espresso-black)]">
            <input
              type="checkbox"
              checked={doNotTrain}
              onChange={(e) => setDoNotTrain(e.target.checked)}
              className="h-4 w-4 accent-[var(--color-brand)]"
            />
            Signal &ldquo;Do not train generative AI&rdquo; preference (advisory only)
          </label>
        </div>

        {/* Step 3: AI Disclosure */}
        <div className="glass-surface p-6 space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <h2 className="text-base font-semibold text-[var(--espresso-black)]">
              3. {t.signer.aiDisclosureHeading}
            </h2>
            <span className="rounded-full bg-[var(--warm-divider)] px-2.5 py-0.5 text-[11px] font-medium text-[var(--warm-stone)]">
              {t.signer.selfDeclaredNote}
            </span>
          </div>

          {hasAiIngredient && (
            <div className="rounded-[16px] border border-amber-200 bg-amber-50 p-3 text-xs text-amber-950">
              An uploaded file contains an AI-labelled ingredient. &ldquo;Made by people, no generative
              AI&rdquo; is disabled (Guardrail G4).
            </div>
          )}

          <div className="grid grid-cols-1 gap-2.5">
            {DISCLOSURE_OPTIONS.map((opt) => {
              const disabledByG4 = hasAiIngredient && opt.value === "no_ai";
              return (
                <label
                  key={opt.value}
                  className={`rounded-[16px] border p-3.5 flex items-start gap-3 cursor-pointer transition-colors duration-150 ${
                    disabledByG4
                      ? "opacity-50 cursor-not-allowed bg-[var(--warm-surface)] border-[var(--border)]"
                      : aiUse === opt.value
                      ? "border-[var(--color-brand)] bg-[var(--warm-peach)]/55"
                      : "border-[var(--border)] bg-white/60 hover:bg-[var(--warm-surface)]"
                  }`}
                >
                  <input
                    type="radio"
                    name="aiUse"
                    value={opt.value}
                    disabled={disabledByG4}
                    checked={aiUse === opt.value}
                    onChange={() => setAiUse(opt.value)}
                    className="mt-1 accent-[var(--color-brand)]"
                  />
                  <div>
                    <div className="text-sm font-medium text-[var(--espresso-black)]">{opt.label}</div>
                    <div className="text-[11px] text-[var(--color-muted)]">{opt.specHint}</div>
                  </div>
                </label>
              );
            })}
          </div>

          {selectedOption.requiresModelType && (
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-2">
              <div className="space-y-1">
                <label htmlFor={modelTypeId} className="block text-xs font-medium text-[var(--espresso-black)]">
                  {t.signer.modelType} *
                </label>
                <select
                  id={modelTypeId}
                  required
                  value={modelType}
                  onChange={(e) => setModelType(e.target.value)}
                  className="w-full glass-input px-3.5 py-2 text-sm"
                >
                  <option value="imageGeneration">imageGeneration</option>
                  <option value="imageEditing">imageEditing</option>
                  <option value="inpainting">inpainting</option>
                  <option value="upscaling">upscaling</option>
                </select>
              </div>
              <div className="space-y-1">
                <label htmlFor={modelNameId} className="block text-xs font-medium text-[var(--espresso-black)]">
                  {t.signer.modelName}
                </label>
                <input
                  id={modelNameId}
                  type="text"
                  placeholder="e.g. Imagen, Flux, Firefly"
                  value={modelName}
                  onChange={(e) => setModelName(e.target.value)}
                  className="w-full glass-input px-3.5 py-2 text-sm"
                />
              </div>
            </div>
          )}
        </div>

        {errorMsg && (
          <div
            role="alert"
            className="rounded-xl border border-[#C83C4D]/30 bg-rose-50 p-4 text-xs text-rose-950 flex flex-wrap items-center justify-between gap-3"
          >
            <div className="flex items-center gap-2">
              <AlertTriangle aria-hidden="true" className="h-4 w-4 shrink-0 text-[#C83C4D]" />
              <span>{errorMsg}</span>
            </div>
            {sessionExpired && (
              <Link
                href="/login?callbackUrl=/app/sign"
                className="btn-plum px-3.5 py-1.5 text-xs font-semibold shrink-0"
              >
                Sign in again
              </Link>
            )}
          </div>
        )}

        <button
          type="submit"
          disabled={submitting || Boolean(invalidExistingFile)}
          className="inline-flex items-center gap-2 btn-plum px-6 py-3 text-sm font-semibold disabled:opacity-50"
        >
          <FileSignature aria-hidden="true" className="h-4 w-4" />
          {submitting
            ? "Submitting batch…"
            : isAuthenticated
            ? `${t.signer.signButton} (${files.length || 0} credits)`
            : "Sign in to sign files"}
        </button>
      </form>
    </div>
  );
}
